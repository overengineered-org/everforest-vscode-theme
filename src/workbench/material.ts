import { Palette, ThemeAppearance } from "../interface";

function getAccessibleAccentGreen(appearance: ThemeAppearance, palette: Palette): string {
  return appearance === "light" ? "#596600" : palette.green;
}

function getReadableTerminalAnsiColors(appearance: ThemeAppearance, palette: Palette) {
  if (appearance === "dark") {
    return {
      black: palette.grey2,
      brightBlack: palette.fg,
      blue: palette.blue,
      cyan: palette.aqua,
      green: palette.green,
      magenta: palette.purple,
      red: palette.red,
      white: palette.fg,
      yellow: palette.yellow,
    };
  }
  return {
    black: "#59646c",
    brightBlack: "#59646c",
    blue: "#2e5f94",
    cyan: "#2f6a4d",
    green: "#596600",
    magenta: "#8a4b7c",
    red: "#ad3d3d",
    white: "#59646c",
    yellow: "#7e5200",
  };
}

